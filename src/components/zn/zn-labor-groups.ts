export function mapLaborCategoryToGroup(category: string | null | undefined): StoLaborGroup {
  if (!category?.trim()) return "ПРОЧЕЕ";
  const direct = OLD_TO_GROUP[category.trim()];
  if (direct) return direct;
  const upper = category.trim().toUpperCase();
  const found = STO_LABOR_GROUPS.find((g) => g.toUpperCase() === upper);
  return found || "ПРОЧЕЕ";
}
