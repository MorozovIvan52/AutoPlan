export function fillPromptTemplate(template: string, ctx: TenantPromptContext): string {
  return template
    .replaceAll("{{tenantName}}", ctx.tenantName || "Автосервис")
    .replaceAll("{{tenantPlan}}", ctx.tenantPlan || "start");
}

/** Готовый системный промт роли с подстановкой тенанта. */
export function getPrompt(role: AgentRole, tenant: TenantPromptContext): string {
  return fillPromptTemplate(PROMPT_TEMPLATES[role], tenant);
}

